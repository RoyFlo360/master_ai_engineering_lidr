"""Consistent pseudonymizer — same input → same pseudonym, every time.

The flow is:

1. Run the analyzer on the input text → list of spans (``entity_type``,
   ``start``, ``end``).
2. For each detected entity, compute an HMAC-SHA256 of the original value with
   the server-side salt. **The HMAC is what the mapping store keys on; the
   plaintext never leaves this function.** That is the property
   ``tests/test_ingestion_security.py`` pins.
3. ``mapping_store.lookup_or_create`` returns a stable pseudonym, generated by a
   type-specific Faker generator on first sight of a given hash.
4. Replace occurrences right-to-left so earlier offsets stay valid as we mutate
   the string.

Reversibility lives in the mapping store, not here: deleting a row by
``(entity_type, original_hash)`` invalidates all future lookups for that value
without touching the corpus.

Determinism: each pseudonym factory is seeded from the HMAC itself, so a given
(salt, value) pair yields the same pseudonym even with an empty store. The
store still matters — it is what makes the mapping reversible and auditable.
"""
from __future__ import annotations

import hashlib
import hmac
from collections.abc import Callable, Sequence
from dataclasses import dataclass
from typing import Any

from faker import Faker

from app.ingestion.pii.mapping_store import MappingStore, PseudonymFactory

DEFAULT_LANGUAGE = "es"

#: The entity types this pipeline treats as personal data.
#:
#: Deliberately narrow. Presidio's Spanish NER also emits ``DATE_TIME``
#: (measured: 0.60 on ``2024-02-14``) and ``URL``; redacting those would replace
#: a signed date with ``REDACTED-xxxxxxxx`` and destroy the factual content the
#: estimator exists to read. A fiscal date is not a personal identifier here, and
#: a URL is normally already inside an email span. Over-redaction is a data-loss
#: bug dressed as privacy, so the allow-list is explicit and testable.
DEFAULT_ENTITIES: tuple[str, ...] = (
    "PERSON",
    "EMAIL_ADDRESS",
    "PHONE_NUMBER",
    "LOCATION",
    "BUDGET_ID",
    "CLIENT_CODE",
)


@dataclass(frozen=True)
class AppliedMapping:
    """One entity that was replaced in the input text."""

    entity_type: str
    original_hash: str
    pseudonym: str
    start: int
    end: int


@dataclass(frozen=True)
class PseudonymizationResult:
    pseudonymized_text: str
    applied: list[AppliedMapping]


class ConsistentPseudonymizer:
    def __init__(
        self,
        *,
        analyzer: Any,
        mapping_store: MappingStore,
        salt: str,
        faker_locale: str = "es_ES",
        language: str = DEFAULT_LANGUAGE,
    ) -> None:
        if not salt:
            raise ValueError("pseudonymization requires a non-empty salt")
        self._analyzer = analyzer
        self._store = mapping_store
        self._salt = salt.encode("utf-8")
        self._language = language
        self._faker = Faker(faker_locale)

    # -- public surface ------------------------------------------------------
    def pseudonymize(
        self,
        text: str,
        *,
        entities: Sequence[str] | None = None,
    ) -> PseudonymizationResult:
        if not isinstance(text, str) or not text:
            return PseudonymizationResult(pseudonymized_text=text or "", applied=[])

        wanted = list(entities) if entities else list(DEFAULT_ENTITIES)
        allowed = set(wanted)
        spans = self._analyzer.analyze(
            text=text, language=self._language, entities=wanted
        )
        # Enforce the allow-list here as well as passing it down. Presidio and
        # the regex fallback honour ``entities``, but a third-party analyzer
        # (or a test stub) may not — and an analyzer that ignores the filter
        # must not be able to redact a date just because it returned one.
        spans = [span for span in spans if span.entity_type in allowed]
        if not spans:
            return PseudonymizationResult(pseudonymized_text=text, applied=[])

        # Resolve overlapping spans deterministically: leftmost first, then the
        # higher-confidence recognizer, then the longer span. Presidio's Spanish
        # NER tags short all-caps identifiers as PERSON too (measured:
        # "CLI-0078" comes back as both CLIENT_CODE 0.95 and PERSON 0.85), so a
        # plain (start, -end) sort made the winner depend on the analyzer's
        # output order. Left to chance, a person pseudonym could overwrite a
        # client code and break traceability. The specific recognizers must win.
        ordered = sorted(
            spans,
            key=lambda span: (span.start, -float(getattr(span, "score", 0.0)), -(span.end - span.start)),
        )
        kept: list[Any] = []
        last_end = -1
        for span in ordered:
            if span.start < 0 or span.end > len(text) or span.start >= span.end:
                continue
            if span.start < last_end:
                continue
            kept.append(span)
            last_end = span.end
        kept.sort(key=lambda span: span.end, reverse=True)

        out = text
        applied: list[AppliedMapping] = []
        for span in kept:
            original_value = text[span.start : span.end]
            entity_type = span.entity_type
            original_hash = self.hash_value(original_value)
            pseudonym = self._store.lookup_or_create(
                entity_type=entity_type,
                original_hash=original_hash,
                new_pseudonym_factory=self._factory(entity_type, original_hash),
            )
            out = out[: span.start] + pseudonym + out[span.end :]
            applied.append(
                AppliedMapping(
                    entity_type=entity_type,
                    original_hash=original_hash,
                    pseudonym=pseudonym,
                    start=span.start,
                    end=span.end,
                )
            )

        return PseudonymizationResult(pseudonymized_text=out, applied=applied)

    def hash_value(self, value: str) -> str:
        """HMAC-SHA256(salt, value) — the only form of the value that is stored."""
        return hmac.new(self._salt, value.encode("utf-8"), hashlib.sha256).hexdigest()

    # -- pseudonym generation ------------------------------------------------
    def _factory(self, entity_type: str, original_hash: str) -> PseudonymFactory:
        """Return a zero-arg factory for this entity type.

        The store calls it only on a miss, so the Faker cost is paid once per
        distinct value. Seeding from the hash makes the output deterministic for
        a given salt even across processes.
        """
        seed = int(original_hash[:12], 16)
        generator = _GENERATORS.get(entity_type)

        def make() -> str:
            if generator is None:
                return f"REDACTED-{original_hash[:8]}"
            self._faker.seed_instance(seed)
            return str(generator(self._faker, seed))

        return make


def _person(faker: Faker, seed: int) -> str:
    return faker.name()


def _email(faker: Faker, seed: int) -> str:
    return faker.ascii_company_email()


def _location(faker: Faker, seed: int) -> str:
    return faker.city()


def _budget_id(faker: Faker, seed: int) -> str:
    return f"BUDGET-{2020 + seed % 10}-{seed % 10000:04d}"


def _client_code(faker: Faker, seed: int) -> str:
    return f"CLI-{seed % 10000:04d}"


_GENERATORS: dict[str, Callable[[Faker, int], str]] = {
    "PERSON": _person,
    "EMAIL_ADDRESS": _email,
    "LOCATION": _location,
    "BUDGET_ID": _budget_id,
    "CLIENT_CODE": _client_code,
}


__all__ = [
    "DEFAULT_ENTITIES",
    "AppliedMapping",
    "ConsistentPseudonymizer",
    "PseudonymizationResult",
]
